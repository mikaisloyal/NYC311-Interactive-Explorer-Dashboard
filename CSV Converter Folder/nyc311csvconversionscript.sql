CREATE DATABASE IF NOT EXISTS nyc311db;
USE nyc311db;
DROP TABLE IF EXISTS nyc311table;
CREATE TABLE nyc311table (
  unique_key                  INT,
  created_date                DATETIME,
  closed_date                 DATETIME,
  agency                      TEXT,
  agency_name                 TEXT,
  problem                     TEXT,
  problem_detail              TEXT,
  additional_details          TEXT,
  location_type               TEXT,
  incident_zip                TEXT,
  incident_address            TEXT,
  street_name                 TEXT,
  cross_street_1              TEXT,
  cross_street_2              TEXT,
  intersection_street_1       TEXT,
  intersection_street_2       TEXT,
  address_type                TEXT,
  city                        TEXT,
  landmark                    TEXT,
  facility_type               TEXT,
  status                      TEXT,
  due_date                    DATETIME,
  resolution_description      TEXT,
  resolution_action_updated   DATETIME,
  community_board             TEXT,
  council_district            INT,
  police_precinct             TEXT,
  bbl                         TEXT,
  borough                     TEXT,
  x_coordinate                INT,
  y_coordinate                INT,
  open_data_channel_type      TEXT,
  park_facility_name          TEXT,
  park_borough                TEXT,
  vehicle_type                TEXT,
  taxi_company_borough        TEXT,
  taxi_pick_up_location       TEXT,
  bridge_highway_name         TEXT,
  bridge_highway_direction    TEXT,
  road_ramp                   TEXT,
  bridge_highway_segment      TEXT,
  latitude                    DECIMAL(14,11),
  longitude                   DECIMAL(14,11),
  location                    TEXT,
  PRIMARY KEY (unique_key)
);

USE nyc311db;

LOAD DATA INFILE ""
INTO TABLE nyc311table
FIELDS TERMINATED BY ','
OPTIONALLY ENCLOSED BY '"'
LINES TERMINATED BY '\n'
IGNORE 1 LINES
(
  @unique_key, @created_date, @closed_date, @agency, @agency_name,
  @problem, @problem_detail, @additional_details, @location_type,
  @incident_zip, @incident_address, @street_name, @cross_street_1,
  @cross_street_2, @intersection_street_1, @intersection_street_2,
  @address_type, @city, @landmark, @facility_type, @status, @due_date,
  @resolution_description, @resolution_action_updated, @community_board,
  @council_district, @police_precinct, @bbl, @borough, @x_coordinate,
  @y_coordinate, @open_data_channel_type, @park_facility_name,
  @park_borough, @vehicle_type, @taxi_company_borough,
  @taxi_pick_up_location, @bridge_highway_name, @bridge_highway_direction,
  @road_ramp, @bridge_highway_segment, @latitude, @longitude, @location
)
SET
  unique_key                = NULLIF(@unique_key, ''),
  created_date              = STR_TO_DATE(NULLIF(@created_date, ''), '%m/%d/%Y %r'),
  closed_date               = STR_TO_DATE(NULLIF(@closed_date, ''), '%m/%d/%Y %r'),
  agency                    = NULLIF(@agency, ''),
  agency_name               = NULLIF(@agency_name, ''),
  problem                   = NULLIF(@problem, ''),
  problem_detail            = NULLIF(@problem_detail, ''),
  additional_details        = NULLIF(@additional_details, ''),
  location_type             = NULLIF(@location_type, ''),
  incident_zip              = NULLIF(@incident_zip, ''),
  incident_address          = NULLIF(@incident_address, ''),
  street_name               = NULLIF(@street_name, ''),
  cross_street_1            = NULLIF(@cross_street_1, ''),
  cross_street_2            = NULLIF(@cross_street_2, ''),
  intersection_street_1     = NULLIF(@intersection_street_1, ''),
  intersection_street_2     = NULLIF(@intersection_street_2, ''),
  address_type              = NULLIF(@address_type, ''),
  city                      = NULLIF(@city, ''),
  landmark                  = NULLIF(@landmark, ''),
  facility_type             = NULLIF(@facility_type, ''),
  status                    = NULLIF(@status, ''),
  due_date                  = STR_TO_DATE(NULLIF(@due_date, ''), '%m/%d/%Y %r'),
  resolution_description    = NULLIF(@resolution_description, ''),
  resolution_action_updated = STR_TO_DATE(NULLIF(@resolution_action_updated, ''), '%m/%d/%Y %r'),
  community_board           = NULLIF(@community_board, ''),
  council_district          = NULLIF(@council_district, ''),
  police_precinct           = NULLIF(@police_precinct, ''),
  bbl                       = NULLIF(@bbl, ''),
  borough                   = NULLIF(@borough, ''),
  x_coordinate              = NULLIF(REPLACE(@x_coordinate, ',', ''), ''),
  y_coordinate              = NULLIF(REPLACE(@y_coordinate, ',', ''), ''),
  open_data_channel_type    = NULLIF(@open_data_channel_type, ''),
  park_facility_name        = NULLIF(@park_facility_name, ''),
  park_borough              = NULLIF(@park_borough, ''),
  vehicle_type              = NULLIF(@vehicle_type, ''),
  taxi_company_borough      = NULLIF(@taxi_company_borough, ''),
